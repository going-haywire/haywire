"""Measure which haywire names the libraries import, for the Author API plan.

Writes workbench/plans/2026-11-15-author-api-names.md. Run from the repo root:

    python3 workbench/playground/author_api_names.py [external-library-dir ...]

A name counts as "documented" when it occurs as a word in docs/**/*.md outside
docs/adr and docs/superpowers. That is a loose test: review the result by hand.
A name's tier is "workbench" when every module it is imported from starts with
one of WORKBENCH_MODULES, otherwise "component".
"""

import ast
import collections
import pathlib
import re
import sys

WORKBENCH_LIBS = {
    "haybale-graph-editor",
    "haybale-studio",
    "haybale-haystack",
    "haybale-marketplace",
    "haybale-share",
}
TEST_LIBS = {"haybale-testing", "haybale-TEST_A"}
WORKBENCH_MODULES = (
    "haywire.ui.panel",
    "haywire.ui.editor",
    "haywire.ui.surface",
    "haywire.ui.elements",
    "haywire.ui.modals",
    "haywire.ui.components",
    "haywire.ui.keymap",
    "haywire.ui.app",
    "haywire.ui.extends",
    "haywire.ui.errors",
    "haywire.ui.utils",
    "haywire.ui.hover_tip",
    "haywire.ui.access_stamp",
    "haywire.core.session",
    "haywire.core.signals",
    "haywire.core.access",
    "haywire.core.state",
    "haywire.core.farmhand",
    "haywire.core.di",
    "haywire.core.undo",
    "haywire.core.graph",
    "haywire.core.host",
    "haywire.barn.builtin.surfaces",
)
OUT = pathlib.Path("workbench/plans/2026-11-15-author-api-names.md")


def main() -> None:
    external = [pathlib.Path(a) for a in sys.argv[1:]]
    roots = [p for p in sorted(pathlib.Path("barn").iterdir()) if p.is_dir()] + external
    external_names = {p.name for p in external}
    use: dict = collections.defaultdict(lambda: collections.defaultdict(collections.Counter))
    for lib in roots:
        for path in lib.rglob("*.py"):
            if ".venv" in path.parts:
                continue
            try:
                tree = ast.parse(path.read_text())
            except (SyntaxError, UnicodeDecodeError):
                continue
            for n in ast.walk(tree):
                if isinstance(n, ast.ImportFrom) and n.module and n.module.startswith("haywire."):
                    for a in n.names:
                        use[a.name][n.module][lib.name] += 1

    words: collections.Counter = collections.Counter()
    for path in pathlib.Path("docs").rglob("*.md"):
        if "adr" in path.parts or "superpowers" in path.parts:
            continue
        words.update(re.findall(r"[A-Za-z_][A-Za-z0-9_]*", path.read_text(errors="ignore")))

    def kind(lib: str) -> str:
        if lib in WORKBENCH_LIBS:
            return "workbench"
        if lib in TEST_LIBS:
            return "test"
        return "external" if lib in external_names else "node"

    rows = []
    for name, mods in use.items():
        libs: collections.Counter = collections.Counter()
        for counter in mods.values():
            libs.update(counter)
        is_wb = all(m.startswith(WORKBENCH_MODULES) or m == "haywire.ui" for m in mods)
        rows.append(
            {
                "name": name,
                "mods": sorted(mods),
                "uses": sum(libs.values()),
                "libs": sorted(libs),
                "kinds": {kind(lib) for lib in libs},
                "documented": words[name] > 0,
                "tier": "workbench" if is_wb else "component",
            }
        )

    def table(selected: list) -> list[str]:
        lines = ["| Name | Imported from | Uses | Libraries |", "|---|---|---|---|"]
        for r in sorted(selected, key=lambda r: (r["mods"][0], r["name"])):
            mods = ", ".join(f"`{m.removeprefix('haywire.')}`" for m in r["mods"])
            libs = ", ".join(lib.removeprefix("haybale-") for lib in r["libs"])
            lines.append(f"| `{r['name']}` | {mods} | {r['uses']} | {libs} |")
        return lines

    def author(r: dict) -> bool:
        return bool(r["kinds"] & {"node", "external"})

    out = [
        "# Author API: measured names",
        "",
        "Generated by `workbench/playground/author_api_names.py`; do not edit by hand.",
        "Appendix to [2026-11-15-author-api.md](2026-11-15-author-api.md). Module paths",
        "are shown without the `haywire.` prefix.",
        "",
        f"{len(rows)} distinct names in total.",
    ]
    for tier in ("component", "workbench"):
        mine = [r for r in rows if r["tier"] == tier]
        cut = [r for r in mine if author(r) and r["documented"]]
        undecided = [r for r in mine if author(r) and not r["documented"]]
        test_only = [r for r in mine if not author(r) and "test" in r["kinds"]]
        wb_only = [r for r in mine if r["kinds"] == {"workbench"}]
        out += ["", f"## {tier.capitalize()} tier: first cut ({len(cut)})", ""]
        out += ["Used by a node-authoring or external library, and documented.", ""] + table(cut)
        out += ["", f"## {tier.capitalize()} tier: to decide ({len(undecided)})", ""]
        out += ["Used by a node-authoring or external library, not documented.", ""] + table(undecided)
        out += ["", f"## {tier.capitalize()} tier: test libraries only ({len(test_only)})", ""]
        out += table(test_only)
        out += ["", f"## {tier.capitalize()} tier: workbench libraries only ({len(wb_only)})", ""]
        out += [f"{sum(r['documented'] for r in wb_only)} of them occur in the docs.", ""] + table(wb_only)
    OUT.write_text("\n".join(out) + "\n")
    print(f"wrote {OUT}: {len(rows)} names")


if __name__ == "__main__":
    main()
