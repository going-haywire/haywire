"""Signal — base class for everything dispatched through SignalBus.

Concrete signal classes (`SelectionMoved`, `GraphDataMutated`, etc.)
inherit directly. `CommandSignal` is the imperative-flavored sub-base.

Synthetic signal classes generated by `signal_field()` also inherit
`Signal` directly — they participate as first-class subclasses with no
special routing.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import ClassVar, Optional

from haywire.core.access.tier import AccessTier


@dataclass(frozen=True, kw_only=True)
class Signal:
    """Base class for everything dispatched through SignalBus.

    Subscribers filter with `isinstance(signal, SignalType)` — there is
    no framework-side identity machinery beyond `type(signal)` matching.

    `cross_session: ClassVar[bool] = False` opts a signal into
    SignalDispatcher.broadcast routing when True.
    """

    cross_session: ClassVar[bool] = False


@dataclass(frozen=True, kw_only=True)
class CommandSignal(Signal):
    """Imperative signal — 'do Y'.

    Conventionally one subscriber per command type (the AppShell), but
    the bus does not enforce that. Travels through the same bus as every
    other signal; the split is vocabulary for authors.
    """


@dataclass(frozen=True, kw_only=True)
class EditorCommand(CommandSignal):
    """A keyboard-invokable command addressed to one editor binding.

    A shortcut publishes the command with the ``binding_id`` of the editor that
    had focus. Only the editor bound to that id receives it, and it is dropped
    when the session's access right is below ``requires``. Subclasses declare
    the class-level metadata; instances carry the target and, for pointer-aware
    commands, where the pointer was.

    Attributes:
        command_id: Stable identifier, unique across commands.
        label: Display name for menus and shortcut lists.
        default_keys: Canonical combos (see ``normalize_combo``) bound by default.
        requires: Access requirement: the minimum tier the session's principal
            must hold for the command to be delivered. Defaults to ``EDIT``.
        native_event: Browser event (e.g. ``"paste"``) that must supply the
            command's data instead of the key press; ``None`` for plain key commands.
        in_text_fields: Whether the command fires while a text field or code
            editor has focus. A focused ``input`` or ``textarea`` is blurred and
            refocused first, so its pending value is committed before the command.
        binding_id: The editor binding the command is addressed to.
        position: Pointer position in the editor's own coordinates, if known.

    Example::

        @dataclass(frozen=True, kw_only=True)
        class Rotate(EditorCommand):
            command_id: ClassVar[str] = "my_lib.rotate"
            label: ClassVar[str] = "Rotate"
            default_keys: ClassVar[tuple[str, ...]] = ("Mod+R",)

        @dataclass(frozen=True, kw_only=True)
        class Inspect(EditorCommand):
            command_id: ClassVar[str] = "my_lib.inspect"
            label: ClassVar[str] = "Inspect"
            requires: ClassVar[AccessTier] = AccessTier.VIEW  # lowered: reads only

        class MyEditor(BaseEditor):
            @react_on(Rotate)
            def _on_rotate(self, signal: Rotate) -> None:
                ...
    """

    command_id: ClassVar[str]
    label: ClassVar[str]
    default_keys: ClassVar[tuple[str, ...]] = ()
    requires: ClassVar[AccessTier] = AccessTier.EDIT
    native_event: ClassVar[Optional[str]] = None
    in_text_fields: ClassVar[bool] = False

    binding_id: str
    position: Optional[tuple[float, float]] = None
